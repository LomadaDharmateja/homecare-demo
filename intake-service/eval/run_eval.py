"""Run the labelled synthetic requests through the agent and write eval/report.md.

Three datasets, from most to least trustworthy:
- final test set (20): written before the last tuning round, run but never inspected for tuning;
- held-out set (30): written later than the tuning set, but its failures guided the last round of rules;
- tuning set (50): prompts and rules were adjusted while looking at its failures.
The final-test number is the honest estimate for unseen requests.

Run from intake-service/:  .\\.venv\\Scripts\\python.exe eval\\run_eval.py
"""
import json
import sys
import time
from collections import Counter
from pathlib import Path

SERVICE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SERVICE_DIR))

from app import agent, db, tools  # noqa: E402
from app.schemas import IntakeIn  # noqa: E402

# Separate database so evaluation runs never mix with the demo data in intake.db.
db.DB_PATH = SERVICE_DIR / "data" / "eval.db"
db.DB_PATH.unlink(missing_ok=True)

DATASETS = [
    ("Final test set (never inspected while tuning)", "final_test_requests.json"),
    ("Held-out set (used for error analysis in the last tuning round)", "holdout_requests.json"),
    ("Tuning set (prompts and rules were adjusted on these)", "synthetic_requests.json"),
]
FIELDS = ["service_type", "urgency", "callback_requested", "preferred_contact_time", "location", "missing_info"]
URGENCY_LEVELS = ["high", "medium", "low"]


def normalise(field, value):
    if field == "location":
        return value.strip().lower() if value else None
    if field == "missing_info":
        return sorted(value or [])
    return value


def evaluate(cases):
    correct, urgency_pairs, failures, seconds = Counter(), Counter(), [], []
    for case in cases:
        start = time.perf_counter()
        record = agent.process_request(IntakeIn(text=case["text"], channel=case["channel"]))
        seconds.append(time.perf_counter() - start)
        wrong = {}
        for field in FIELDS:
            expected, predicted = normalise(field, case["labels"][field]), normalise(field, record[field])
            if expected == predicted:
                correct[field] += 1
            else:
                wrong[field] = {"expected": expected, "predicted": predicted}
        urgency_pairs[(case["labels"]["urgency"], record["urgency"])] += 1
        if wrong:
            failures.append({"id": case["id"], "language": case["language"], "text": case["text"], "wrong": wrong})
        print(f"case {case['id']:>3}: {'ok' if not wrong else 'wrong: ' + ', '.join(wrong)}  ({seconds[-1]:.1f}s)")
    return {"total": len(cases), "correct": correct, "urgency_pairs": urgency_pairs,
            "failures": failures, "avg_seconds": sum(seconds) / len(cases)}


def summary_lines(title, result):
    total, correct, pairs = result["total"], result["correct"], result["urgency_pairs"]
    all_correct = total - len(result["failures"])
    high_total = sum(count for (expected, _), count in pairs.items() if expected == "high")
    lines = [f"## {title}: {total} cases", "", "| Field | Correct | Accuracy |", "|---|---|---|"]
    lines += [f"| {field} | {correct[field]}/{total} | {correct[field] / total:.0%} |" for field in FIELDS]
    lines += [
        "",
        f"- All six fields correct: **{all_correct}/{total} ({all_correct / total:.0%})**",
        f"- High-urgency recall (high cases labelled high): **{pairs[('high', 'high')]}/{high_total}**",
        f"- Average time per request (full agent loop, local GPU): {result['avg_seconds']:.1f}s",
        "",
        "Urgency confusion (rows = expected, columns = predicted):",
        "",
        "| expected \\ predicted | high | medium | low |",
        "|---|---|---|---|",
    ]
    lines += [
        f"| {expected} | " + " | ".join(str(pairs[(expected, predicted)]) for predicted in URGENCY_LEVELS) + " |"
        for expected in URGENCY_LEVELS
    ]
    return lines


def failure_lines(title, result):
    lines = [f"### Failures in {title.split(' (')[0].lower()} ({len(result['failures'])} cases with at least one wrong field)", ""]
    for failure in result["failures"]:
        details = "; ".join(f"{field}: expected `{v['expected']}`, got `{v['predicted']}`" for field, v in failure["wrong"].items())
        lines.append(f"- **#{failure['id']}** ({failure['language']}) {details}  \n  > {failure['text']}")
    return lines + [""]


def main():
    results = []
    for title, filename in DATASETS:
        print(f"\n== {title}")
        cases = json.loads((SERVICE_DIR / "data" / filename).read_text(encoding="utf-8"))
        results.append((title, evaluate(cases)))

    lines = [
        "# Evaluation report",
        "",
        f"Model: `{tools.MODEL_NAME}` via Ollama, temperature 0. Every request runs through the full agent loop. "
        "Generated by `eval/run_eval.py`.",
        "",
        "Comparison rules: location is compared case-insensitively; missing_info must match as a set.",
        "",
        "**Caveat:** all cases are synthetic and were labelled by the same author who wrote the prompts.",
        "Tuning-set and held-out numbers are optimistic because their failures guided the prompts and rules.",
        "The final test set is the honest estimate for new requests, but 20 cases is a small sample:",
        "one case is 5 percentage points. Results also vary by a case or two between runs, even at temperature 0.",
        "",
    ]
    for title, result in results:
        lines += summary_lines(title, result) + [""]
    for title, result in results:
        lines += failure_lines(title, result)

    report_path = SERVICE_DIR / "eval" / "report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    for title, result in results:
        print("\n".join(summary_lines(title, result)[:13]))
    print(f"\nReport written to {report_path}")


if __name__ == "__main__":
    main()
